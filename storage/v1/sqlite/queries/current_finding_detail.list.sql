SELECT scope_id,
       subject_id,
       run_id,
       finding_id,
       title,
       severity,
       fingerprint,
       validity,
       resolution,
       assurance,
       category,
       cwes,
       effective_severity,
       family,
       ownership,
       business_unit,
       tree,
       is_branch_audit,
       cvss_score,
       triage_verdict,
       triage_severity,
       exposure_class
FROM current_finding_detail
WHERE scope_id IN (SELECT value FROM json_each(:scope_ids))
ORDER BY scope_id, subject_id, run_id, finding_id, title;
